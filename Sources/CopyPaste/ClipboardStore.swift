import AppKit
import CryptoKit

final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()

    @Published private(set) var items: [ClipItem] = []
    @Published var paused = false

    let baseDir: URL
    let imagesDir: URL
    private var dataFile: URL { baseDir.appendingPathComponent("history.json") }

    private var lastChangeCount = NSPasteboard.general.changeCount
    private var pollTimer: Timer?
    private var cleanupTimer: Timer?
    private var saveWork: DispatchWorkItem?
    private let ioQueue = DispatchQueue(label: "copypaste.io")

    /// Pasteboard markers used by password managers & co. — never stored.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
        "com.typeit4me.clipping", "net.antelle.keeweb",
    ]

    private init() {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        baseDir = support.appendingPathComponent("CopyPaste", isDirectory: true)
        imagesDir = baseDir.appendingPathComponent("images", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
        load()
    }

    func start() {
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        pollTimer = t
        enforceLimits()
        let c = Timer(timeInterval: 600, repeats: true) { [weak self] _ in self?.enforceLimits() }
        RunLoop.main.add(c, forMode: .common)
        cleanupTimer = c
    }

    // MARK: Capture

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        guard !paused else { return }
        capture(pb)
    }

    private func capture(_ pb: NSPasteboard) {
        guard let types = pb.types, !types.isEmpty else { return }
        if types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) { return }

        let app = NSWorkspace.shared.frontmostApplication
        let appName = app?.localizedName
        let bundleID = app?.bundleIdentifier
        let now = Date()

        // Files copied in Finder
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let joined = urls.map(\.path).joined(separator: "\n")
            insert(ClipItem(kind: .file, text: joined, sourceAppName: appName, sourceBundleID: bundleID,
                            firstCopied: now, date: now, contentHash: Self.hash("file", Data(joined.utf8))))
            return
        }

        // Text
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let kind = Classifier.kind(for: s, bundleID: bundleID)
            insert(ClipItem(kind: kind, text: s, sourceAppName: appName, sourceBundleID: bundleID,
                            firstCopied: now, date: now, contentHash: Self.hash("text", Data(s.utf8))))
            return
        }

        // Image
        guard AppSettings.shared.saveImages else { return }
        var png = pb.data(forType: .png)
        if png == nil, let img = NSImage(pasteboard: pb), let tiff = img.tiffRepresentation,
           let rep = NSBitmapImageRep(data: tiff) {
            png = rep.representation(using: .png, properties: [:])
        }
        guard let data = png, let rep = NSBitmapImageRep(data: data) else { return }
        let item = ClipItem(kind: .image, imageFile: UUID().uuidString + ".png",
                            imageWidth: rep.pixelsWide, imageHeight: rep.pixelsHigh,
                            sourceAppName: appName, sourceBundleID: bundleID,
                            firstCopied: now, date: now, contentHash: Self.hash("image", data))
        insert(item, imageData: data)
    }

    private static func hash(_ prefix: String, _ data: Data) -> String {
        var h = SHA256()
        h.update(data: Data(prefix.utf8))
        h.update(data: data)
        return h.finalize().map { String(format: "%02x", $0) }.joined()
    }

    private func insert(_ new: ClipItem, imageData: Data? = nil) {
        if let idx = items.firstIndex(where: { $0.contentHash == new.contentHash }) {
            var existing = items.remove(at: idx)
            existing.date = new.date
            existing.useCount += 1
            existing.sourceAppName = new.sourceAppName ?? existing.sourceAppName
            existing.sourceBundleID = new.sourceBundleID ?? existing.sourceBundleID
            items.insert(existing, at: 0)
        } else {
            if let data = imageData, let file = new.imageFile {
                try? data.write(to: imagesDir.appendingPathComponent(file))
            }
            items.insert(new, at: 0)
        }
        enforceLimits()
        scheduleSave()
    }

    // MARK: Actions

    /// Puts the item on the system clipboard (it becomes the next ⌘V) and moves it to the top.
    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .image:
            guard let file = item.imageFile,
                  let data = try? Data(contentsOf: imagesDir.appendingPathComponent(file)) else { return }
            let pbItem = NSPasteboardItem()
            pbItem.setData(data, forType: .png)
            if let tiff = NSImage(data: data)?.tiffRepresentation { pbItem.setData(tiff, forType: .tiff) }
            pb.writeObjects([pbItem])
        case .file:
            pb.writeObjects(item.fileURLs as [NSURL])
        default:
            pb.setString(item.text ?? "", forType: .string)
        }
        lastChangeCount = pb.changeCount

        if let idx = items.firstIndex(where: { $0.id == item.id }) {
            var updated = items.remove(at: idx)
            updated.date = Date()
            updated.useCount += 1
            items.insert(updated, at: 0)
            scheduleSave()
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[idx].pinned.toggle()
        scheduleSave()
    }

    func delete(_ item: ClipItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        removeFiles(of: [items.remove(at: idx)])
        scheduleSave()
    }

    func clear(keepPinned: Bool = true) {
        let removed = items.filter { !keepPinned || !$0.pinned }
        items.removeAll { !keepPinned || !$0.pinned }
        removeFiles(of: removed)
        scheduleSave()
    }

    func enforceLimits() {
        let s = AppSettings.shared
        var removed: [ClipItem] = []
        if s.retentionHours > 0 {
            let cutoff = Date().addingTimeInterval(-Double(s.retentionHours) * 3600)
            removed += items.filter { !$0.pinned && $0.date < cutoff }
            items.removeAll { !$0.pinned && $0.date < cutoff }
        }
        let unpinned = items.filter { !$0.pinned }
        if unpinned.count > s.maxItems {
            let extra = Set(unpinned.suffix(unpinned.count - s.maxItems).map(\.id))
            removed += items.filter { extra.contains($0.id) }
            items.removeAll { extra.contains($0.id) }
        }
        if !removed.isEmpty {
            removeFiles(of: removed)
            scheduleSave()
        }
    }

    private func removeFiles(of removed: [ClipItem]) {
        for item in removed {
            if let f = item.imageFile {
                try? FileManager.default.removeItem(at: imagesDir.appendingPathComponent(f))
                ImageCache.shared.evict(f)
            }
        }
    }

    // MARK: Persistence

    private func load() {
        guard let data = try? Data(contentsOf: dataFile),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded.filter { item in
            guard let f = item.imageFile else { return true }
            return FileManager.default.fileExists(atPath: imagesDir.appendingPathComponent(f).path)
        }
    }

    private func scheduleSave() {
        saveWork?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.saveNow() }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 1, execute: work)
    }

    func saveNow() {
        let snapshot = items
        let url = dataFile
        ioQueue.sync {
            if let data = try? JSONEncoder().encode(snapshot) {
                try? data.write(to: url, options: .atomic)
            }
        }
    }
}

// MARK: - Image cache

final class ImageCache {
    static let shared = ImageCache()
    private let cache = NSCache<NSString, NSImage>()
    private var appIcons: [String: NSImage] = [:]

    func thumbnail(for item: ClipItem, maxPixel: Int = 120) -> NSImage? {
        guard let f = item.imageFile else { return nil }
        let key = "\(f)-\(maxPixel)" as NSString
        if let c = cache.object(forKey: key) { return c }
        let url = ClipboardStore.shared.imagesDir.appendingPathComponent(f)
        guard let src = CGImageSourceCreateWithURL(url as CFURL, nil) else { return nil }
        let opts: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixel,
            kCGImageSourceCreateThumbnailWithTransform: true,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, opts as CFDictionary) else { return nil }
        let img = NSImage(cgImage: cg, size: NSSize(width: cg.width, height: cg.height))
        cache.setObject(img, forKey: key)
        return img
    }

    func fullImage(for item: ClipItem) -> NSImage? {
        guard let f = item.imageFile else { return nil }
        return NSImage(contentsOf: ClipboardStore.shared.imagesDir.appendingPathComponent(f))
    }

    func evict(_ file: String) {
        for size in [80, 120, 240, 400] { cache.removeObject(forKey: "\(file)-\(size)" as NSString) }
    }

    func appIcon(bundleID: String?) -> NSImage? {
        guard let b = bundleID else { return nil }
        if let i = appIcons[b] { return i }
        guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: b) else { return nil }
        let icon = NSWorkspace.shared.icon(forFile: url.path)
        appIcons[b] = icon
        return icon
    }
}
